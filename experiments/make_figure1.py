"""The schematic figure, emitted as a TikZ fragment.

The figure has one job: show where the representation enters the decision, and why that
entry point is a ceiling. A reader who takes only this away should be able to say that the
partition's reliability caps what a person can tell you, and that the cap plus forgetting
decides whether the question can be answered at all.

The accumulator on the right is drawn from the deployed parameters rather than sketched,
so the two traces really do straddle the boundary and the crossing really does happen
where the caption says. A schematic that disagrees with the arithmetic it illustrates is
worse than no schematic.

Run:  python3 experiments/make_figure1.py
"""
from __future__ import annotations

import math

import common as P
from cfas import waggle

OUT = P.REPO / "figures" / "model.tex"
TPR, FPR = 0.918, 0.3889
TAU = 30.0
AREA = 36.17                 # the part with the least slack
HORIZON = 105.0              # minutes drawn
X_SCALE = 6.6 / HORIZON      # tikz units per minute
Y_SCALE = 2.55 / 2.6         # tikz units per nat


def trace(jump: float, dt: float, horizon: float = HORIZON, step: float = 0.6):
    """The accumulator sampled finely enough that the decay reads as a curve."""
    pts, t, level, last = [], 0.0, 0.0, 0.0
    arrivals = [i * dt for i in range(int(horizon / dt) + 1)]
    while t <= horizon:
        level = sum(jump * math.exp(-(t - a) / TAU) for a in arrivals if a <= t)
        pts.append((t, level))
        t += step
    return pts


def path(pts, dx=0.0):
    return " ".join(f"({dx + x * X_SCALE:.3f},{y * Y_SCALE:.3f})" for x, y in pts)


def main():
    with P.calibrated(TPR, FPR):
        lam = waggle.llr("HIGH")
        a, _ = waggle.thresholds(AREA)
        dt_star = -TAU * math.log(1 - lam / a)
    fast, slow = dt_star * 0.75, dt_star * 1.6
    below = trace(lam, slow)
    above = trace(lam, fast)
    cross = next(t for t, v in above if v >= a)

    tex = rf"""% Generated by experiments/make_figure1.py. Do not edit by hand.
\begin{{tikzpicture}}[
  box/.style={{draw=black!55, rounded corners=2pt, align=center, inner sep=4pt,
               font=\small, minimum height=7mm, text width=32mm}},
  flow/.style={{-{{Latex[length=1.6mm]}}, draw=black!70}},
  lbl/.style={{font=\scriptsize, align=left}}]

% ---- (a) where the representation enters --------------------------------------
\node[box] (H) at (0,4.6) {{part $g$ is in hazard\\[-1pt]\footnotesize the hypothesis}};
\node[box] (C) at (0,2.6) {{the cell a resident\\[-1pt]stands in is wet}};
\node[box] (B) at (0,0.6) {{the band they report}};

\draw[flow] (H) -- node[right, lbl, xshift=1mm]
  {{$\mathrm{{TPR}},\ \mathrm{{FPR}}$\\ the partition}} (C);
\draw[flow] (C) -- node[right, lbl, xshift=1mm]
  {{$s_b,\ f_b$\\ the instrument}} (B);

\draw[decorate, decoration={{brace, amplitude=4pt, mirror}}, draw=black!55]
  (-2.05,0.25) -- (-2.05,4.95);
\node[rotate=90, anchor=south, font=\scriptsize] at (-2.3,2.6)
  {{one report is worth $\Lambda(b)$ nats}};
\node[font=\small, align=center] at (0,-0.85)
  {{$\Lambda(b)\ \le\ \kappa=\log\dfrac{{\mathrm{{TPR}}}}{{\mathrm{{FPR}}}}$}};
\node[font=\scriptsize, text width=42mm, align=center, black!65] at (0,-1.95)
  {{however honest the reporter, however good the instrument}};
\node[font=\small\bfseries] at (-2.3,5.35) {{(a)}};

% ---- (b) whether the question can be answered ---------------------------------
\begin{{scope}}[xshift=52mm]
  \draw[draw=black!45] (0,0) -- ({6.9:.3f},0);
  \draw[draw=black!45] (0,0) -- (0,{2.55 + 0.35:.3f});
  \draw[dashed, draw=black!70] (0,{a * Y_SCALE:.3f}) -- ({6.9:.3f},{a * Y_SCALE:.3f});
  \node[font=\scriptsize, anchor=south west, black!70]
    at (0.1,{a * Y_SCALE:.3f}) {{escalate at $A$}};

  \draw[draw=black!80, line width=0.9pt] plot coordinates {{{path(above)}}};
  \draw[draw=black!45, line width=0.9pt, densely dotted]
    plot coordinates {{{path(below)}}};

  \fill[black] ({cross * X_SCALE:.3f},{a * Y_SCALE:.3f}) circle (1.5pt);
  \node[font=\scriptsize, anchor=west, xshift=1mm]
    at ({cross * X_SCALE:.3f},{a * Y_SCALE + 0.3:.3f}) {{decided}};
  \node[font=\scriptsize, anchor=west, align=left, black!55]
    at ({4.4:.3f},{max(v for _, v in below) * Y_SCALE - 0.45:.3f})
    {{$\Delta t>\Delta t^{{*}}$: never decided,\\at a fixed interval}};
  \node[font=\scriptsize, anchor=north] at ({3.45:.3f},-0.15) {{time}};
  \node[rotate=90, font=\scriptsize, anchor=south] at (-0.35,{1.3:.3f})
    {{accumulated nats}};
  \node[font=\small\bfseries] at (-0.4,5.35) {{(b)}};
  \node[font=\scriptsize, text width=62mm, align=center, black!65] at ({3.45:.3f},-1.15)
    {{each arrival adds at most $\kappa$ and then leaks at the hazard's own rate, so
      below a critical interval the boundary is out of reach}};
\end{{scope}}
\end{{tikzpicture}}
"""
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(tex)
    print(f"wrote {OUT}")
    print(f"  Lambda {lam:.3f}  A {a:.3f}  dt* {dt_star:.1f} min")
    print(f"  drawn: crossing trace at {fast:.1f} min, stalled trace at {slow:.1f} min")
    print(f"  crossing occurs at {cross:.0f} min; stalled peak "
          f"{max(v for _, v in below):.3f} nats against A {a:.3f}")


if __name__ == "__main__":
    main()
